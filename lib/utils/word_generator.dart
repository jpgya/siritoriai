  /// 指定された頭文字から始まる動的単語リストを連続生成する
  static List<WordEntry> generateWordsForKana(String startKana, Set<String> existingReadings) {
    List<WordEntry> generated = [];
    String normStart = KanaUtils.normalizeKana(startKana);

    // 1. ベース語根の取得
    List<Map<String, String>> roots = _baseRoots[normStart] ?? [
      {'w': normStart, 'r': normStart}
    ];

    for (var root in roots) {
      String w = root['w']!;
      String r = root['r']!;

      // そのままの単語
      _addIfValid(w, r, "標準語", generated, existingReadings);

      // 接尾辞を付加した複合単語を動的に多重生成（「～性」「～化」「～力」など）
      for (var suf in _suffixes) {
        String newW = w + suf['s']!;
        String newR = r + suf['r']!;
        _addIfValid(newW, newR, suf['cat']!, generated, existingReadings);
      }
    }

    // 2. もし手詰まりになりそうな「る」などの特殊文字の場合、さらに拡張複合単語を自動生み出す
    if (generated.isEmpty) {
      _fallbackGenerate(normStart, generated, existingReadings);
    }

    return generated;
  }

  static void _addIfValid(
    String word,
    String reading,
    String cat,
    List<WordEntry> list,
    Set<String> existingReadings,
  ) {
    if (reading.endsWith('ん') || reading.endsWith('ン')) return;
    if (existingReadings.contains(reading)) return;

    String start = KanaUtils.getStartKana(reading);
    String end = KanaUtils.getEndKana(reading);

    if (start.isNotEmpty && end.isNotEmpty) {
      list.add(WordEntry(
        word: word,
        reading: reading,
        startKana: start,
        endKana: end,
        category: cat,
        description: "AI動的生成単語",
      ));
    }
  }

  /// 万が一のフォールバック：完全に新規の言語的パターンを組み立てる
  static void _fallbackGenerate(
    String startKana,
    List<WordEntry> list,
    Set<String> existingReadings,
  ) {
    const fallbackSuffixes = [
      {'w': 'システム', 'r': 'しすてむ'},
      {'w': 'エリア', 'r': 'えりあ'},
      {'w': 'モード', 'r': 'もーど'},
      {'w': 'ライン', 'r': 'らいん'},
      {'w': 'フェーズ', 'r': 'ふぇーず'},
    ];

    for (var suf in fallbackSuffixes) {
      String word = startKana + suf['w']!;
      String reading = startKana + suf['r']!;
      _addIfValid(word, reading, "造語・新技術", list, existingReadings);
    }
  }
